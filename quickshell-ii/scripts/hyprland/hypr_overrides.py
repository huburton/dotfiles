#!/usr/bin/env python3
"""Shell-side Hyprland option overrides (game mode, anti-flashbang...) for
hyprland-git's Lua config.

hyprconfigurator.py edits hyprland/shellOverrides/main.conf, which the Lua
config never reads. This keeps the overrides in shell-overrides.json, renders
~/.config/hypr/shell-overrides.lua (loaded by hyprland.lua) and applies them:
live with `hyprctl eval` for --set, with `hyprctl reload` for --reset (back to
config.lua values plus the remaining overrides).

Usage: hypr_overrides.py [--set KEY VALUE]... [--reset KEY]...
Keys use Hyprland's colon syntax, e.g. decoration:blur:enabled.
"""
import argparse
import json
import os
import subprocess

HYPR = os.path.expanduser("~/.config/hypr")
STATE = os.path.join(HYPR, "shell-overrides.json")
LUA = os.path.join(HYPR, "shell-overrides.lua")


def lua_value(value):
    if value in ("true", "false"):
        return value
    try:
        float(value)
        return value
    except ValueError:
        return json.dumps(value)


def lua_table(entries):
    tree = {}
    for key, value in entries.items():
        *path, leaf = key.split(":")
        node = tree
        for part in path:
            node = node.setdefault(part, {})
        node[leaf] = value

    def render(node):
        return "{ " + ", ".join(
            f'["{k}"] = {render(v) if isinstance(v, dict) else lua_value(v)}'
            for k, v in node.items()) + " }"
    return render(tree)


parser = argparse.ArgumentParser()
parser.add_argument("--set", nargs=2, action="append", default=[], metavar=("KEY", "VALUE"))
parser.add_argument("--reset", action="append", default=[], metavar="KEY")
args = parser.parse_args()

state = {}
if os.path.exists(STATE):
    with open(STATE) as f:
        state = json.load(f)
for key, value in args.set:
    state[key] = value
for key in args.reset:
    state.pop(key, None)

with open(STATE, "w") as f:
    json.dump(state, f, indent=2)
with open(LUA, "w") as f:
    f.write("-- Generated by quickshell scripts/hyprland/hypr_overrides.py. Do not edit.\n")
    if state:
        f.write(f"pcall(hl.config, {lua_table(state)})\n")

if args.reset:
    subprocess.run(["hyprctl", "reload"], check=False)
elif args.set:
    subprocess.run(["hyprctl", "eval", f"hl.config({lua_table(dict(args.set))})"], check=False)
